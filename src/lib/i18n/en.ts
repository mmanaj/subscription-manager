const s = (n: number, word: string) => `${n} ${word}${n === 1 ? "" : "s"}`;

function cycle(unit: IntervalUnit, count: number): string {
  if (count === 1) return { day: "daily", week: "weekly", month: "monthly", year: "yearly" }[unit];
  if (unit === "month" && count === 3) return "quarterly";
  if (unit === "month" && count === 6) return "every 6 months";
  return `every ${s(count, unit)}`;
}

